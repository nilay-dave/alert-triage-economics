"""Measure frontier runtime and the headline figures across corpus sizes.

Writes raw results to benchmark/results/. Every number the README publishes
about performance comes from a run of this file, and tools/check_numbers.py
fails CI when a documented number no longer matches a measured one.

Usage:
    python benchmark/run_benchmark.py [--sizes 50000 500000 2000000]
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd  # noqa: E402

from ate.config import Config  # noqa: E402
from ate.corpus.generate import generate  # noqa: E402
from ate.frontier.summary import analyse  # noqa: E402
from ate.logging import configure  # noqa: E402

RESULTS = Path(__file__).parent / "results"
DEFAULT_SIZES = (50_000, 500_000, 2_000_000)
REPEATS = 3


def _hardware() -> dict:
    import os

    return {
        "platform": platform.platform(),
        "python": platform.python_version(),
        "processor": platform.machine(),
        "cpu_count": os.cpu_count(),
    }


def _time(fn, repeats: int):
    samples, value = [], None
    for _ in range(repeats):
        start = time.perf_counter()
        value = fn()
        samples.append(time.perf_counter() - start)
    samples.sort()
    return value, {
        "repeats": repeats,
        "min_s": round(samples[0], 4),
        "median_s": round(statistics.median(samples), 4),
        "max_s": round(samples[-1], 4),
    }


def run(sizes, repeats, workdir: Path, reuse: bool) -> dict:
    configure("WARNING")
    config = Config()
    workdir.mkdir(parents=True, exist_ok=True)
    scenarios = []

    for size in sizes:
        corpus = workdir / f"bench_{size}.parquet"
        if reuse and corpus.exists():
            generation = {"repeats": 0, "median_s": None, "reused": True}
        else:
            _, generation = _time(lambda c=corpus, n=size: generate(c, n, seed=7), 1)

        frame = pd.read_parquet(corpus)
        summary, timing = _time(lambda f=frame: analyse(f, config), repeats)

        scenarios.append({
            "alerts": size,
            "corpus_bytes": corpus.stat().st_size,
            "generate": generation,
            "analyse": timing,
            "alerts_per_second": round(size / timing["median_s"]),
            "bootstrap_resamples": config.bootstrap_resamples,
            "bootstrap_noise_cap": config.bootstrap_noise_cap,
            "true_positives": summary.true_positives,
            "one_in": round(1 / summary.tp_rate) if summary.tp_rate else None,
            "rules_analysed": summary.rules_analysed,
            "free_volume_pct": round(summary.free_volume_pct, 2),
            "free_hours": round(summary.free_hours, 1),
            "untunable_rules": [f.rule for f in summary.untunable],
            "untunable_volume_pct": round(summary.untunable_volume_pct, 2),
            "blanket_cut_cost": {str(f): round(summary.cost_of(f), 2) for f in (0.1, 0.25, 0.5, 0.75, 0.9)},
        })
        if not reuse:
            corpus.unlink(missing_ok=True)
        print(
            f"  {size:>12,} alerts  analyse {timing['median_s']:>8.3f}s  "
            f"free {summary.free_volume_pct:>5.1f}%  half costs {summary.cost_of(0.5):>5.1f}%"
        )

    return {
        "hardware": _hardware(),
        "repeats": repeats,
        "corpus": "synthetic, generated by ate generate at seed 7",
        "scenarios": scenarios,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sizes", type=int, nargs="+", default=list(DEFAULT_SIZES))
    parser.add_argument("--repeats", type=int, default=REPEATS)
    parser.add_argument("--workdir", type=Path, default=Path("data/generated/bench"))
    parser.add_argument("--reuse", action="store_true", help="Reuse and keep corpora instead of regenerating.")
    args = parser.parse_args()

    print(f"benchmarking {len(args.sizes)} corpus sizes, {args.repeats} repeats each")
    payload = run(tuple(args.sizes), args.repeats, args.workdir, args.reuse)

    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / "benchmark.json"
    out.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
