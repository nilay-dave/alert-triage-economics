"""Collect every number this repository publishes into docs/metrics.json.

The README, the badges, the charts and the explainer video all read their
numbers from this file rather than carrying their own copies.
tools/check_numbers.py then fails CI when a published figure no longer matches
a measured one.

Usage:
    python tools/collect_metrics.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402

from ate.config import Config  # noqa: E402
from ate.corpus.generate import generate  # noqa: E402
from ate.corpus.spec import load_spec  # noqa: E402
from ate.frontier.summary import analyse  # noqa: E402
from ate.logging import configure  # noqa: E402

BENCHMARK = ROOT / "benchmark" / "results" / "benchmark.json"
COVERAGE_XML = ROOT / "coverage.xml"
OUT = ROOT / "docs" / "metrics.json"
HEADLINE_ALERTS = 500_000
HEADLINE_SEED = 7


def _coverage_pct() -> float | None:
    if not COVERAGE_XML.exists():
        return None
    rate = ET.parse(COVERAGE_XML).getroot().get("line-rate")
    return round(float(rate) * 100, 1) if rate else None


def _test_count() -> int | None:
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q"],
        cwd=ROOT, capture_output=True, text=True,
    )
    total = 0
    for line in result.stdout.splitlines():
        head, _, tail = line.rpartition(":")
        if head.endswith(".py") and tail.strip().isdigit():
            total += int(tail.strip())
    return total or None


def _commit_count() -> int | None:
    result = subprocess.run(["git", "rev-list", "--count", "HEAD"], cwd=ROOT, capture_output=True, text=True)
    return int(result.stdout.strip()) if result.returncode == 0 else None


def _headline() -> dict:
    configure("WARNING")
    config = Config()
    corpus = ROOT / "data" / "generated" / f"metrics_{HEADLINE_ALERTS}.parquet"
    if not corpus.exists():
        generate(corpus, HEADLINE_ALERTS, seed=HEADLINE_SEED)
    summary = analyse(pd.read_parquet(corpus), config)
    spec = load_spec()
    return {
        "corpus_alerts": HEADLINE_ALERTS,
        "corpus_seed": HEADLINE_SEED,
        "corpus_kind": "synthetic",
        "true_positives": summary.true_positives,
        "one_in": round(1 / summary.tp_rate),
        "rules_declared": len(spec.rules),
        "rules_analysed": summary.rules_analysed,
        "free_volume": summary.free_volume,
        "free_volume_pct": round(summary.free_volume_pct, 1),
        "free_hours": round(summary.free_hours),
        "minutes_per_alert": config.minutes_per_alert,
        "untunable_rule_count": len(summary.untunable),
        "untunable_rules": [f.rule for f in summary.untunable],
        "untunable_volume_pct": round(summary.untunable_volume_pct, 1),
        "untunable_true_positives": sum(f.true_positives for f in summary.untunable),
        "blanket_cut_cost": {str(f): round(summary.cost_of(f), 1) for f in (0.1, 0.25, 0.5, 0.75, 0.9)},
        "best_rule": max(summary.frontiers, key=lambda f: f.volume_removed_at_first_loss).rule,
        "best_rule_free_pct": round(
            100 * max(f.volume_removed_at_first_loss for f in summary.frontiers), 1
        ),
        "bootstrap_resamples": config.bootstrap_resamples,
        "confidence_pct": round(config.confidence * 100),
    }


def main() -> int:
    payload: dict = {
        "note": (
            "Generated by tools/collect_metrics.py. Numbers derived from the bundled synthetic "
            "corpus are simulations and are labelled as such wherever they are published."
        ),
        "analysis": _headline(),
        "quality": {
            "test_coverage_pct": _coverage_pct(),
            "test_count": _test_count(),
            "commit_count": _commit_count(),
        },
    }

    if BENCHMARK.exists():
        benchmark = json.loads(BENCHMARK.read_text(encoding="utf-8"))
        payload["performance"] = {
            "hardware": benchmark["hardware"],
            "repeats": benchmark["repeats"],
            "scenarios": [
                {
                    "alerts": s["alerts"],
                    "corpus_mb": round(s["corpus_bytes"] / 1e6, 1),
                    "analyse_median_s": s["analyse"]["median_s"],
                    "alerts_per_second": s["alerts_per_second"],
                    "bootstrap_resamples": s["bootstrap_resamples"],
                }
                for s in benchmark["scenarios"]
            ],
        }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(json.dumps(payload["analysis"], indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
